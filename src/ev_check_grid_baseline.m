function checks = ev_check_grid_baseline(runs, csvPath, tolerance)
% Read existing baseline exports without modifying them. Only matched seeds.
checks=table(zeros(0,1),false(0,1),false(0,1), ...
    'VariableNames',{'Seed','BatteryEnabled','Passed'});
if ~isfile(csvPath), return; end
baseline=readtable(csvPath,'TextType','string');
fields={'VehicleCount','MeanWaitMinutes','P95WaitMinutes','MaxWaitMinutes', ...
    'MaxQueueLength','LastEVCompletionMinutes','ThroughputVehiclesPerHour', ...
    'TotalGridWaitMinutes','MeanGridWaitMinutes','FullGridBlocks','PeakGridLoadKW', ...
    'AverageGridUtilizationPercent','BatteryEnergyUsedKWh','BatteryAssistedSessions','MinimumBatteryEnergyKWh'};
old={'generated_vehicle_count','mean_wait_minutes','p95_wait_minutes','max_wait_minutes', ...
    'max_queue_length','last_vehicle_completion_time','throughput_vehicles_per_hour', ...
    'total_grid_wait_minutes','mean_grid_wait_minutes','full_grid_blocks','peak_grid_load_kW', ...
    'average_grid_utilization_percent','battery_energy_used_kWh','battery_assisted_sessions','minimum_battery_energy_kWh'};
for i=find(runs.GridCapacityKW==200)'
    name='No_Battery'; if runs.BatteryEnabled(i), name='Baseline_Battery'; end
    b=baseline(baseline.seed==runs.Seed(i) & strcmp(baseline.scenario_name,name),:);
    if isempty(b), continue; end
    assert(height(b)==1,'Duplicate stored baseline row.');
    assert(all(abs(runs{i,fields}-b{1,old})<=tolerance+1e-8), ...
        '200 kW result differs from the stored baseline for seed %d (%s).',runs.Seed(i),name);
    checks=[checks;table(runs.Seed(i),runs.BatteryEnabled(i),true, ...
        'VariableNames',checks.Properties.VariableNames)]; %#ok<AGROW>
end
end
