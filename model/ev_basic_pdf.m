function png = ev_basic_pdf()
%EV_BASIC_PDF Petri net structure for a basic EV charging station.

png.PN_name = 'Basic EV Charging Station';

% pToArrive limits the total arrivals; pArrivalReady allows one at a time.
% All three charger types share the queue and completed-vehicle place.
% Each charger has its own availability token and charging place.
png.set_of_Ps = { ...
    'pToArrive', 'pArrivalReady', 'pWait', 'pDispatch', ...
    'pAvailNormal', 'pAvailMedium', 'pAvailFast', ...
    'pChargeNormal', 'pChargeMedium', 'pChargeFast', 'pDone' ...
};

% Separate timed completion transitions allow simultaneous charging.
png.set_of_Ts = { ...
    'tArrival', 'tRecharge', 'tStartNormal', 'tDoneNormal', ...
    'tStartMedium', 'tDoneMedium', 'tStartFast', 'tDoneFast' ...
};

% pDispatch locks only allocation until COMMON_POST reserves its power.
% Charging paths remain independent and can run concurrently.
% Each arc is defined by its source, destination, and token weight.
png.set_of_As = { ...
    'pDispatch', 'tRecharge', 1, ...
    'tRecharge', 'pDispatch', 1, ...
    'pDispatch', 'tStartNormal', 1, ...
    'tStartNormal', 'pDispatch', 1, ...
    'pDispatch', 'tStartMedium', 1, ...
    'tStartMedium', 'pDispatch', 1, ...
    'pDispatch', 'tStartFast', 1, ...
    'tStartFast', 'pDispatch', 1, ...
    'pToArrive',     'tArrival',      1, ...
    'pArrivalReady', 'tArrival',      1, ...
    'tArrival',     'pWait',         1, ...
    'tArrival',     'pArrivalReady', 1, ...
    'pWait',    'tStartNormal',  1, ...
    'pAvailNormal',  'tStartNormal',  1, ...
    'tStartNormal',  'pChargeNormal', 1, ...
    'pChargeNormal', 'tDoneNormal',   1, ...
    'tDoneNormal',   'pDone',    1, ...
    'tDoneNormal',   'pAvailNormal',  1, ...
    'pWait',    'tStartMedium',  1, ...
    'pAvailMedium',  'tStartMedium',  1, ...
    'tStartMedium',  'pChargeMedium', 1, ...
    'pChargeMedium', 'tDoneMedium',   1, ...
    'tDoneMedium',   'pDone',    1, ...
    'tDoneMedium',   'pAvailMedium',  1, ...
    'pWait',        'tStartFast',  1, ...
    'pAvailFast',   'tStartFast',  1, ...
    'tStartFast',   'pChargeFast', 1, ...
    'pChargeFast',  'tDoneFast',   1, ...
    'tDoneFast',    'pDone',       1, ...
    'tDoneFast',    'pAvailFast',  1 ...
};

% Each arrival consumes one pToArrive token permanently and returns the
% pArrivalReady token, enabling the next arrival if any vehicles remain.

end

