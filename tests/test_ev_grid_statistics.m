function test_ev_grid_statistics()
% Regression fixture from the verified 200 kW run (no GPenSIM required).
v = table({'A';'B';'C';'A';'B';'C'}, [22;50;150;22;50;150], ...
    {'Normal';'Medium';'Fast';'Medium';'Normal';'Fast'}, ...
    [2;4.01;6.02;8.03;10.04;12.05], ...
    [2;4.01;28.02;28.03;29.29;44.04], ...
    [2.01;4.02;28.03;28.04;29.30;44.05], ...
    [29.29;28.02;44.04;82.59;111.12;64.06], ...
    [22;50;150;22;22;150], 'VariableNames', ...
    {'VehicleType','MaxChargingKW','Charger','ArrivalTime','AllocationStart', ...
    'ChargingStart','CompletionTime','EffectiveChargingKW'});
v.QueueWait = v.AllocationStart - v.ArrivalTime;
v.WaitingTime = v.ChargingStart - v.ArrivalTime;
e = table([2.01;4.02;28.02;28.03;28.04;29.29;29.30;44.04;44.05;64.06;82.59;111.12], ...
    [22;72;22;172;194;172;194;44;194;44;22;0], ...
    'VariableNames', {'TimeMinutes','LoadAfterKW'});
[g, result] = ev_grid_statistics(v, e, 200, [22;50;150]);
assert(g.fullBlocks == 1 && g.preferenceBlocks == 0);
assert(max(abs(result.GridWaitMinutes - [0;0;22;0;0;0])) < 1e-9);
assert(g.peakLoadKW == 194 && g.finalLoadKW == 0);
% Independent integration from each vehicle's measured charging duration.
expectedArea = sum((v.CompletionTime-v.ChargingStart).*v.EffectiveChargingKW);
assert(abs(g.averageLoadKW - expectedArea/111.12) < 1e-9);
% Duplicate timestamps must not add time or create extra blocking events.
e = sortrows([e; e(2,:)], 'TimeMinutes');
[duplicate, ~] = ev_grid_statistics(v, e, 200, [22;50;150]);
assert(abs(duplicate.averageLoadKW-g.averageLoadKW) < 1e-9);
assert(duplicate.fullBlocks == 1);

% A synthetic allocation: C prefers free Fast, but only Medium fits.
f = table({'C';'C'}, [150;150], {'Normal';'Medium'}, [0;1], [0;1], ...
    [0.01;1.01], [5;3], [22;50], 'VariableNames', ...
    {'VehicleType','MaxChargingKW','Charger','ArrivalTime','AllocationStart', ...
    'ChargingStart','CompletionTime','EffectiveChargingKW'});
% First vehicle must prefer Normal, so use Type A with its 22 kW limit.
f.VehicleType{1} = 'A'; f.MaxChargingKW(1) = 22;
f.QueueWait = [0;0]; f.WaitingTime = [0.01;0.01];
fe = table([0.01;1.01;3;5], [22;72;22;0], ...
    'VariableNames', {'TimeMinutes','LoadAfterKW'});
[fallback, ~] = ev_grid_statistics(f, fe, 100, [22;50;150]);
assert(fallback.preferenceBlocks == 1 && fallback.fullBlocks == 0);
disp('Grid history, weighted average, blocking episodes, fallback and waiting checks passed.');
end
