function [fire, transition] = tRecharge_pre(transition)
% Read-only: recharge only after this finite EV workload is finished.
global PN global_info;
names = {PN.global_places.name};
fire = PN.X(strcmp(names,'pDone')) == numel(global_info.vehicleTypes) ...
    && PN.X(strcmp(names,'pWait')) == 0 ...
    && all(global_info.activeVehicle == 0) ...
    && global_info.currentBatteryDischargeKW == 0 ...
    && global_info.batteryEnergyKWh < global_info.BATTERY_CAPACITY_KWH - 1e-9;
end
